export type TrialKey = keyof typeof WORDS;

export const TRIAL_MESSAGES: Record<string, string> = Object.fromEntries(
  Object.entries(WORDS).map(([key, value]) => [`trial.${key}`, value]),
);

registerMessages(TRIAL_MESSAGES);

export function w(key: TrialKey, params: Record<string, string | number | null | undefined> = {}): string {
  return t(`trial.${key}`, params);
}

/** A plural key's words: `key_one` or `key_other` by `count`. */
export function wn(key: string, count: number, params: Record<string, string | number | null | undefined> = {}): string {
  return t(`trial.${key}`, { ...params, count });
}
