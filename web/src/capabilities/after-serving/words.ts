type Plural<K> = K extends `${infer B}_${"one" | "other"}` ? B : never;
export type AfterKey = keyof typeof WORDS | Plural<keyof typeof WORDS>;

export const AFTER_MESSAGES: Record<string, string> = Object.fromEntries(
  Object.entries(WORDS).map(([key, value]) => [`after_serving.${key}`, value]),
);

export function registerAfterMessages(): void {
  registerMessages(AFTER_MESSAGES);
}

export function w(key: AfterKey, params: Record<string, string | number | null | undefined> = {}): string {
  return t(`after_serving.${key}`, params);
}

