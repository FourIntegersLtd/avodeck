type Plural<K> = K extends `${infer B}_${"one" | "other"}` ? B : never;
export type ReportKey = keyof typeof WORDS | Plural<keyof typeof WORDS>;

export const REPORT_MESSAGES: Record<string, string> = Object.fromEntries(
  Object.entries(WORDS).map(([key, value]) => [`report.${key}`, value]),
);

export function registerReportMessages(): void {
  registerMessages(REPORT_MESSAGES);
}

export function w(key: ReportKey, params: Record<string, string | number | null | undefined> = {}): string {
  return t(`report.${key}`, params);
}

registerReportMessages();
