export type OrgKey = keyof typeof WORDS;

export const ORG_MESSAGES: Record<string, string> = Object.fromEntries(Object.entries(WORDS).map(([key, value]) => [`organisations.${key}`, value]));

export function registerOrganisationMessages(): void {
  registerMessages(ORG_MESSAGES);
}

export function w(key: OrgKey, params: Record<string, string | number | null | undefined> = {}): string {
  return t(`organisations.${key}`, params);
}

/** "1 year" / "6 years": the plural forms are registered under this key. */
export function yearsText(count: number): string {
  const key = "organisations.rules.retention_years";
  return t(key, { count });
}

/** "6 cases", "1 case", or a dash for none. */
export function casesText(count: number): string {
  const key = "organisations.people.cases";
  return count > 0 ? t(key, { count }) : w("people.cases_none");
}

registerOrganisationMessages();
