# ============================================================ GP referral documents (typed, born-digital or scanned)
def ers_document(doc_id, *, kind, sent: date, sender, service, body, summary=True, ubrn=None):
    """An e-Referral Service style referral or A&G request letter generated from the GP system."""
    d = Doc(doc_id, "referral", margin_l=18 * mm, margin_r=18 * mm)
    d.text(d.ml, f"{kind}", "Sans-B", 13, lead=18)
    d.text(d.ml, f"Unique booking reference: {ubrn or R.randint(100000000000, 999999999999)}", "Sans", 9)
    for k, v in [("Patient", f"{P['title']} {P['first']} {P['last']}"), ("DOB", uk_date(P["dob"])), ("NHS number", fmt_nhs(P["nhs"])),
                 ("Address", ", ".join(P["address"])), ("Referrer", f"{sender}, {PRACTICE['name']} ({PRACTICE['ods']})"),
                 ("Service", service), ("Date sent", uk_date(sent))]:
        d.text(d.ml, k, "Sans-B", 9.5, advance=False)
        d.text(d.ml + 38 * mm, v, "Sans", 9.5)
    d.printed_date(sent)
    d.y -= 4
    d.hline()
    d.y -= 14
    for para in body:
        d.para(d.ml, para, W - d.ml - d.mr, "Sans", 10, lead=13.5)
        d.y -= 6
    d.text(d.ml, sender, "Sans-B", 10)
    d.fact("referral", kind, event_date=sent, service=service)
    if summary:
        d.page_break()
        d.text(d.ml, "Attached patient summary (generated by the practice system)", "Sans-B", 11, lead=18)
        for title, rows in [("Active problems", ["18-Jun-2012 Essential hypertension", "02-Nov-2001 Hypothyroidism",
                                                  "15-May-2024 Iron deficiency anaemia" if sent >= date(2024, 5, 15) else "12-Feb-2024 Tiredness symptom"]),
                            ("Current medication", ["Amlodipine 5mg tablets - one daily", "Levothyroxine 75microgram tablets - one daily"] +
                             (["Ferrous fumarate 210mg tablets - one three times a day"] if sent >= date(2024, 5, 15) else [])),
                            ("Allergies", ["No known drug allergy"]),
                            ("Recent results", ["14-Feb-2024 Haemoglobin 112 g/L (L), MCV 77 fL (L), Ferritin 9 ug/L (L)"] +
                             (["13-May-2024 Haemoglobin 104 g/L (L), MCV 75 fL (L)"] if sent >= date(2024, 5, 13) else [])),
                            ("Recent values", ["Body weight 64.2 kg (15-May-2024)" if sent >= date(2024, 5, 15) else "BP 138/84 (12-Feb-2024)"] +
                             (["Body weight 63.1 kg (24-Jun-2024)"] if sent >= date(2024, 6, 24) else []) +
                             (["Body weight 61.8 kg (20-Aug-2024)"] if sent >= date(2024, 8, 20) else []))]:
            d.text(d.ml, title, "Sans-B", 10, lead=14)
            for row in rows:
                d.text(d.ml + 5 * mm, row, "Sans", 9.5)
                if "Ferritin 9" in row:
                    d.fact("result", "9 ug/L", quote="Ferritin 9 ug/L", event_date="2024-02-14", test="Ferritin")
            d.y -= 6
    return d


