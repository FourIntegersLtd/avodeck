# ============================================================ charts drawn as images
def fluid_chart(day: date, seed: int, trust="Westvale University Hospitals"):
    rng = random.Random(seed)
    img = Image.new("RGB", (PW, PH), (252, 252, 250))
    d = ImageDraw.Draw(img)
    _label(d, trust, "FLUID BALANCE CHART")
    d.text((60, 70), f"Date: {uk_date(day)}", font=_font(14), fill=0)
    cols = ["Time", "IV", "Oral", "Total in", "Urine", "Drain", "Vomit", "Total out"]
    cw = (PW - 120) // len(cols)
    y0 = 170
    for j, c in enumerate(cols):
        d.rectangle([60 + j * cw, y0, 60 + (j + 1) * cw, y0 + 36], outline=(90, 90, 90), fill=(225, 232, 240))
        d.text((66 + j * cw, y0 + 9), c, font=_font(13, True), fill=0)
    hand = pick_hand(rng, 0.55)
    ink = rng.choice(INKS)
    tin = tout = 0
    for i, hr in enumerate(range(8, 32, 2)):
        y = y0 + 36 + i * 52
        iv = rng.choice([0, 0, 100, 125]) if day.day <= 22 else 0
        oral = rng.choice([0, 50, 100, 150, 200])
        ur = rng.choice([0, 0, 150, 200, 250])
        tin += iv + oral
        tout += ur
        vals = [f"{hr % 24:02d}:00", str(iv or ""), str(oral or ""), str(tin), str(ur or ""), "", "", str(tout)]
        for j, v in enumerate(vals):
            d.rectangle([60 + j * cw, y, 60 + (j + 1) * cw, y + 52], outline=(190, 190, 190))
            if v:
                hand_text(img, (70 + j * cw, y + 36), v, rng, size=25, messy=0.5, hand=hand, ink=ink)
    hand_text(img, (80, y0 + 36 + 13 * 52 + 40), f"24h balance {tin - tout:+d} ml", rng, size=28, messy=0.5, hand=hand, ink=ink)
    pi = PageInfo(f"p2-fluid-{day.isoformat()}", 1, "hospital_notes")
    pi.printed_dates.append(day.isoformat())
    pi.facts.append(Fact("examination", f"24h balance {tin - tout:+d} ml", f"+{tin - tout} ml", day.isoformat(), {"chart": "fluid", "handwritten": True}))
    return img, pi


def anaesthetic_record(day: date, seed: int, trust, procedure, anaesthetist):
    rng = random.Random(seed)
    img = Image.new("RGB", (PW, PH), (252, 252, 250))
    d = ImageDraw.Draw(img)
    _label(d, trust, "ANAESTHETIC RECORD")
    d.text((60, 70), f"Date: {uk_date(day)}   Procedure: {procedure}   Anaesthetist: {anaesthetist}", font=_font(13), fill=0)
    gx, gy, gw, gh = 120, 200, PW - 200, 520
    for i in range(13):
        d.line([(gx + i * gw / 12, gy), (gx + i * gw / 12, gy + gh)], fill=(210, 210, 225))
    for j in range(11):
        d.line([(gx, gy + j * gh / 10), (gx + gw, gy + j * gh / 10)], fill=(210, 210, 225))
        d.text((gx - 50, gy + j * gh / 10 - 7), str(200 - j * 20), font=_font(11), fill=0)
    ink = rng.choice(INKS)
    sys_, dia, hr = 130, 75, 78
    for i in range(24):
        x = gx + i * gw / 24
        sys_ += rng.randint(-8, 6); dia += rng.randint(-5, 4); hr += rng.randint(-4, 4)
        for val, ch in ((sys_, "v"), (dia, "^"), (hr, ".")):
            y = gy + (200 - val) / 200 * gh
            hand_text(img, (int(x), int(y)), ch, rng, size=30, messy=0.3, ink=ink)
    hand = pick_hand(rng, 0.6)
    notes = ["GA. Propofol 150 fentanyl 100 rocuronium 50", "ETT 7.0 grade 1. Art line R radial", "Sevo/air/O2. Paracetamol 1g, ondansetron 4",
             "Dexamethasone 6.6. Co-amoxiclav 1.2g", "Blood loss 150 ml. Fluids 1500 ml CSL", "Extubated awake. To recovery stable"]
    for k, n in enumerate(notes):
        hand_text(img, (80, gy + gh + 80 + k * 52), n, rng, size=27, messy=0.6, hand=hand, ink=ink)
    pi = PageInfo(f"p2-anaes-{day.isoformat()}", 1, "hospital_notes")
    pi.printed_dates.append(day.isoformat())
    pi.facts.append(Fact("examination", "Blood loss 150 ml", "Blood loss 150 ml", day.isoformat(), {"chart": "anaesthetic", "handwritten": True}))
    return img, pi


def ctg_strip(day: date, seed: int, page_no: int):
    rng = random.Random(seed)
    img = Image.new("RGB", (PW, PH), (252, 246, 240))
    d = ImageDraw.Draw(img)
    d.text((60, 40), f"CTG  {P['first']} ASHWORTH  {uk_date(day)}  sheet {page_no}", font=_font(15, True), fill=0)
    for band, (top, lo, hi) in enumerate([(120, 50, 210), (900, 0, 100)]):
        hgt = 620 if band == 0 else 360
        for i in range(0, PW - 120, 20):
            d.line([(60 + i, top), (60 + i, top + hgt)], fill=(235, 190, 190) if i % 100 else (210, 140, 140))
        for j in range(0, hgt + 1, 20):
            d.line([(60, top + j), (PW - 60, top + j)], fill=(235, 190, 190) if j % 100 else (210, 140, 140))
        pts, v = [], 140 if band == 0 else 10
        for x in range(60, PW - 60, 3):
            if band == 0:
                v += rng.uniform(-3, 3); v = min(160, max(120, v))
                if rng.random() < 0.01:
                    v += 15
            else:
                t = (x - 60) / 260.0
                v = 10 + 70 * max(0, math.sin(t * math.pi)) ** 3
            y = top + hgt - (v - lo) / (hi - lo) * hgt
            pts.append((x, y))
        d.line(pts, fill=(30, 30, 30), width=2)
    ink = rng.choice(INKS)
    hand_text(img, (80, 820), rng.choice(["Reactive. Baseline 140, variability >5, accels present, no decels",
                                          "Normal CTG. MW to review hourly", "Contractions 3:10. FH normal"]), rng, size=28, messy=0.6, ink=ink)
    pi = PageInfo(f"p2-ctg-{day.isoformat()}-{page_no}", 1, "hospital_notes")
    pi.printed_dates.append(day.isoformat())
    pi.facts.append(Fact("examination", "CTG baseline 140", "Baseline 140", day.isoformat(), {"chart": "ctg", "handwritten": True}))
    return img, pi


def checklist_form(day: date, seed: int, trust, title, items):
    rng = random.Random(seed)
    img = Image.new("RGB", (PW, PH), (252, 252, 250))
    d = ImageDraw.Draw(img)
    _label(d, trust, title)
    y = 190
    ink = rng.choice(INKS)
    hand = pick_hand(rng, 0.5)
    for section, rows in items:
        d.rectangle([60, y, PW - 60, y + 34], fill=(225, 225, 225), outline=(150, 150, 150))
        d.text((70, y + 8), section, font=_font(14, True), fill=0)
        y += 46
        for row in rows:
            d.rectangle([70, y, 98, y + 28], outline=(60, 60, 60), width=2)
            hand_text(img, (72, y + 26), "/", rng, size=34, messy=0.3, ink=ink)
            d.text((115, y + 5), row, font=_font(14), fill=0)
            y += 42
        y += 10
    hand_text(img, (80, y + 50), f"Signed {rng.choice(['L Hart', 'K Thomas', 'M Obi'])} {day.day}/{day.month}/{str(day.year)[2:]}",
              rng, size=27, messy=0.5, hand=hand, ink=ink)
